export function swishStoreKey(raw) {
  let s = String(raw || '').toLowerCase().trim();
  s = s.replace(/['’׳"`״]/g, '');
  s = s.replace(/&/g, ' ');
  s = s.replace(/[-־–—]/g, ' ');
  s = s.replace(/[()]/g, ' ');
  s = s.replace(/\s+/g, ' ').trim();
  s = s.replace(/^רשת\s+/, '');
  s = s.replace(/\s+(אונליין|און ליין|online)$/g, '').trim();
  return s;
}

const SWISH_PREFIX_REMAINDERS = new Set(['ישראל', 'קידס', 'kids', 'הום', 'home', 'פורצלן', 'קליניק', 'ספא', 'אונליין', 'online']);

function swishKeyCovers(storeKey, candidate) {
  if (!candidate || !storeKey) return false;
  if (storeKey === candidate) return true;
  const storeCompact = storeKey.replace(/\s+/g, '');
  const candCompact = candidate.replace(/\s+/g, '');
  if (candCompact.length >= 6 && storeCompact === candCompact) return true;
  if (/^[a-z0-9 ]+$/.test(candidate) && candCompact.length >= 6) {
    const leadingLatin = (storeKey.match(/^[a-z0-9 ]+/) || [''])[0].trim();
    if (leadingLatin && leadingLatin.replace(/\s+/g, '') === candCompact) return true;
  }
  if (candidate.length >= 8 && storeKey.startsWith(`${candidate} `)) return true;
  if (candidate.length >= 4 && storeKey.startsWith(`${candidate} `)) {
    const rest = storeKey.slice(candidate.length + 1);
    const first = rest.split(' ')[0];
    if (SWISH_PREFIX_REMAINDERS.has(first)) return true;
  }
  return false;
}

/** True when this merchant name (or one of its catalog aliases) is on the Swish Plus list. */
export function merchantOnSwishPlus(merchantName, merchData) {
  const candidates = new Set();
  const add = (value) => {
    const key = swishStoreKey(value);
    if (key) candidates.add(key);
  };
  add(merchantName);
  const paren = String(merchantName || '').match(/\(([^)]+)\)\s*$/);
  if (paren) add(paren[1]);
  add(String(merchantName || '').replace(/\s*\([^)]*\)\s*$/, ''));
  for (const alias of merchData?.aliases || []) add(alias);
  for (const candidate of candidates) {
    for (const storeKey of SWISH_PLUS_KEYS) {
      if (swishKeyCovers(storeKey, candidate)) return true;
    }
  }
  return false;
}
